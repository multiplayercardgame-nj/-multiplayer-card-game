    "                if not name or not 2 <= maximum <= 10:\n",
    "                    await send_error(\n",
    "                        ws, \"Enter a name and a player limit from 2 to 10.\"\n",
    "                    )\n",
    "                    continue\n",
    "\n",
    "                code = make_room_code()\n",
    "\n",
    "                player = {\n",
    "                    \"id\": str(uuid.uuid4()),\n",
    "                    \"name\": name,\n",
    "                    \"ws\": ws,\n",
    "                    \"hand\": []\n",
    "                }\n",
    "\n",
    "                room = {\n",
    "                    \"code\": code,\n",
    "                    \"host_id\": player[\"id\"],\n",
    "                    \"max_players\": maximum,\n",
    "                    \"players\": [player],\n",
    "                    \"deck\": [],\n",
    "                    \"top_card\": None,\n",
    "                    \"current_turn\": None,\n",
    "                    \"started\": False,\n",
    "                    \"winner\": None\n",
    "                }\n",
    "\n",
    "                rooms[code] = room\n",
    "\n",
    "                await ws.send_json({\n",
    "                    \"type\": \"room_created\",\n",
    "                    \"room_code\": code\n",
    "                })\n",
    "                await broadcast_state(room)\n",
    "\n",
    "            # Join an existing room\n",
    "            elif action == \"join_room\":\n",
    "                if player:\n",
    "                    await send_error(ws, \"You already joined a room.\")\n",
    "                    continue\n",
    "\n",
    "                code = str(data.get(\"room_code\", \"\")).strip().upper()\n",
    "                name = str(data.get(\"name\", \"\")).strip()[:20]\n",
    "                target = rooms.get(code)\n",
    "\n",
    "                if not name:\n",
    "                    await send_error(ws, \"Enter a player name.\")\n",
    "                elif target is None:\n",
    "                    await send_error(ws, \"Room not found.\")\n",
    "                elif target[\"started\"]:\n",
    "                    await send_error(ws, \"The game has already started.\")\n",
    "                elif len(target[\"players\"]) >= target[\"max_players\"]:\n",
    "                    await send_error(ws, \"Room is full.\")\n",
    "                else:\n",
    "                    room = target\n",
    "                    player = {\n",
