    "            # Start game (host only)\n",
    "            elif action == \"start_game\":\n",
    "                if player[\"id\"] != room[\"host_id\"]:\n",
    "                    await send_error(ws, \"Only the host can start.\")\n",
    "                elif room[\"started\"]:\n",
    "                    await send_error(ws, \"Game has already started.\")\n",
    "                elif len(room[\"players\"]) < 2:\n",
    "                    await send_error(ws, \"At least 2 players are required.\")\n",
    "                else:\n",
    "                    initialize_game(room)\n",
    "                    await broadcast_state(room)\n",
    "\n",
    "            # Play a card\n",
    "            elif action == \"play_card\":\n",
    "                if not room[\"started\"] or room[\"winner\"]:\n",
    "                    await send_error(ws, \"The game is not active.\")\n",
    "                    continue\n",
    "\n",
    "                if room[\"current_turn\"] != player[\"id\"]:\n",
    "                    await send_error(ws, \"It is not your turn.\")\n",
    "                    continue\n",
    "\n",
    "                card = data.get(\"card\")\n",
    "                if not isinstance(card, str) or card not in player[\"hand\"]:\n",
    "                    await send_error(ws, \"You do not have that card.\")\n",
    "                    continue\n",
    "\n",
    "                rank, suit = card[:-1], card[-1]\n",
    "                top_rank, top_suit = (\n",
    "                    room[\"top_card\"][:-1],\n",
    "                    room[\"top_card\"][-1]\n",
    "                )\n",
    "\n",
    "                # Example rule: match rank OR suit.\n",
    "                if rank != top_rank and suit != top_suit:\n",
    "                    await send_error(\n",
    "                        ws, \"Match the rank or suit of the top card.\"\n",
    "                    )\n",
    "                    continue\n",
    "\n",
    "                player[\"hand\"].remove(card)\n",
    "                room[\"top_card\"] = card\n",
    "\n",
    "                if not player[\"hand\"]:\n",
    "                    room[\"winner\"] = player[\"name\"]\n",
    "                else:\n",
    "                    next_turn(room)\n",
    "\n",
    "                await broadcast_state(room)\n",
    "\n",
    "            # Draw a card\n",
    "            elif action == \"draw_card\":\n",
    "                if (\n",
    "                    not room[\"started\"]\n",
    "                    or room[\"winner\"]\n",
    "                    or room[\"current_turn\"] != player[\"id\"]\n",
    "                ):\n",
    "                    await send_error(ws, \"You cannot draw now.\")\n",
    "                    continue\n",
    "\n",
    "                if not room[\"deck\"]:\n",
    "                    await send_error(ws, \"The deck is empty.\")\n",
    "                    continue\n",
    "\n",
    "                player[\"hand\"].append(room[\"deck\"].pop())\n",
    "                next_turn(room)\n",
    "                await broadcast_state(room)\n",
    "\n",
    "            # Pass turn\n",
    "            elif action == \"pass_turn\":\n",
    "                if (\n",
    "                    not room[\"started\"]\n",
    "                    or room[\"winner\"]\n",
    "                    or room[\"current_turn\"] != player[\"id\"]\n",
    "                ):\n",
    "                    await send_error(ws, \"You cannot pass now.\")\n",
    "                    continue\n",
    "\n",
    "                next_turn(room)\n",
    "                await broadcast_state(room)\n",
    "\n",
    "            else:\n",
    "                await send_error(ws, \"Unknown action.\")\n",
    "\n",
    "    except WebSocketDisconnect:\n",
    "        pass\n",
    "    except Exception as error:\n",
    "        print(\"Client connection error:\", error)\n",
    "\n",
    "    finally:\n",
    "        if room is not None and player is not None:\n",
    "            if player in room[\"players\"]:\n",
    "                was_current = room[\"current_turn\"] == player[\"id\"]\n",
    "                room[\"players\"].remove(player)\n",
    "\n",
    "                if not room[\"players\"]:\n",
    "                    rooms.pop(room[\"code\"], None)\n",
    "                else:\n",
    "                    if room[\"host_id\"] == player[\"id\"]:\n",
    "                        room[\"host_id\"] = room[\"players\"][0][\"id\"]\n",
    "\n",
    "                    if was_current:\n",
    "                        room[\"current_turn\"] = room[\"players\"][0][\"id\"]\n",
    "\n",
    "                    await broadcast_state(room)\n",
    "\n",
    "        try:\n",
    "            await ws.close()\n",
    "        except Exception:\n",
    "            pass"
